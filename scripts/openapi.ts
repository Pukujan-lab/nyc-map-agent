/**
 * pnpm openapi        write openapi.json and its client types from the Hono route table
 * pnpm openapi:check  fail if either is stale or a route has no spec
 */
import { readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";
import { app, MOUNTED_PATHS } from "../server/app";
import { API_INFO, ROUTES } from "../server/openapi";

const missing = MOUNTED_PATHS.filter((p) => !(p in ROUTES));
if (missing.length) {
  console.error(`Routes without an OpenAPI spec in server/openapi.ts: ${missing.join(", ")}`);
  process.exit(1);
}
const TYPES = "src/lib/api/schema.d.ts";
const doc = app.getOpenAPI31Document({ openapi: "3.1.0", info: API_INFO });
const text = JSON.stringify(doc, null, 2) + "\n";
// openapi-typescript reads the document we just built, so the types match it exactly.
const types =
  "/* Generated by `pnpm openapi` from openapi.json; do not edit. */\n" +
  astToString(await openapiTS(text, { alphabetize: true }));
const read = (file: string) => {
  try {
    return readFileSync(file, "utf8");
  } catch {
    return "";
  }
};
if (process.argv.includes("--check")) {
  const stale = [read("openapi.json") !== text && "openapi.json", read(TYPES) !== types && TYPES].filter(Boolean);
  if (stale.length) {
    console.error(`${stale.join(" and ")} stale: run \`pnpm openapi\` and commit.`);
    process.exit(1);
  }
  console.log(`openapi.json and ${TYPES} up to date (${Object.keys(doc.paths ?? {}).length} paths)`);
} else {
  writeFileSync("openapi.json", text);
  writeFileSync(TYPES, types);
  console.log(`wrote openapi.json and ${TYPES} (${Object.keys(doc.paths ?? {}).length} paths)`);
}
